"""构建部署用 CSS 与 WOFF2 字体；可在任意目录运行，路径始终相对项目根目录。"""
import argparse
import hashlib
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "assets/css"


def bundle(name, sources):
    """按原有覆盖顺序合并样式，并将相对资源 URL 改写到目标 CSS 所在目录。"""
    parts = ["/* Generated by tools/build_assets.py; edit the source files. */\n"]
    for source in sources:
        path = ROOT / source
        text = path.read_text(encoding="utf-8")

        def rebase(match):
            url = match.group(2)
            # data: 内嵌字体、绝对 URL 和锚点不参与文件系统路径重写。
            if re.match(r"(?:[a-z]+:|/|#)", url, re.I):
                return match.group(0)
            relative = os.path.relpath((path.parent / url).resolve(), CSS)
            return 'url("' + Path(relative).as_posix() + '")'

        text = re.sub(r'url\(([\"\']?)([^)\"\']+)\1\)', rebase, text)
        # 合并时去掉源样式中既有的行尾空白，避免生成产物引入无意义的差异。
        text = "\n".join(line.rstrip(" \t") for line in text.splitlines()) + "\n"
        parts.append("/* " + source + " */\n" + text + "\n")
    (CSS / name).write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8", newline="\n")


def unicode_ranges(points):
    """合并连续码点；保留范围间的空洞，避免浏览器为不存在的字符选择错误分片。"""
    ranges = []
    start = end = points[0]
    for point in points[1:]:
        if point == end + 1:
            end = point
        else:
            ranges.append((start, end))
            start = end = point
    ranges.append((start, end))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def build_fonts():
    """保留 TTF 作为构建源；线上服务器直接使用预先生成的文件，不需要构建工具。"""
    from fontTools import subset
    from fontTools.ttLib import TTFont

    output = ROOT / "assets/fonts/web"
    output.mkdir(exist_ok=True)
    faces = ["/* Generated by tools/build_assets.py; preserve the font OFL licenses. */"]
    for style, weight, italic in [
        ("Regular", 400, False), ("Italic", 400, True),
        ("Bold", 700, False), ("BoldItalic", 700, True),
    ]:
        source = ROOT / f"assets/fonts/JetBrainsMonoNL/JetBrainsMonoNL-{style}.ttf"
        # 固定时间戳，避免相同输入因构建时间不同而改变字体内容及缓存 URL。
        font = TTFont(source, recalcTimestamp=False)
        font.flavor = "woff2"
        # 使用各字重/斜体准确的本地全名，不能把 Regular 错当成 Bold 或 Italic。
        local_name = next(n.toUnicode() for n in font["name"].names
                          if n.nameID == 4 and n.platformID == 3)
        filename = save_font(font, output, f"JetBrainsMonoNL-{style}")
        faces.append(font_face("JetBrains Mono NL", filename, weight,
                               "italic" if italic else "normal", local_name))

    source = ROOT / "assets/fonts/LXGWWenKaiScreen/LXGWWenKaiScreen.ttf"
    with TTFont(source) as font:
        points = sorted(font.getBestCmap())
    # 按实际字形每 256 个分片，覆盖全部字符，包括扩展区和罕见字。
    # 浏览器根据 unicode-range 下载所需分片，不再请求完整的 18.9 MB TTF。
    for index, offset in enumerate(range(0, len(points), 256)):
        chunk = points[offset:offset + 256]
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=chunk)
        # 保留默认 OpenType 布局闭包，不能为减少几个符号而破坏字体组合/镜像规则。
        # 实际分片选择严格受下面的 unicode-range 限制；测试会验证范围完整且不重叠。
        subsetter.subset(font)
        font.flavor = "woff2"
        filename = save_font(font, output, f"LXGWWenKaiScreen-{index:03}")
        faces.append(font_face("LXGW Wenkai Screen", filename, 400, "normal",
                               "LXGW WenKai Screen", unicode_ranges(chunk)))
        if index % 25 == 0:
            print(f"Chinese font subsets: {index + 1}", flush=True)
    (CSS / "webfonts.css").write_text("\n\n".join(faces) + "\n", encoding="utf-8", newline="\n")


def save_font(font, output, stem):
    """文件名带内容摘要，服务器可以对 WOFF2 使用长期 immutable 缓存。"""
    from io import BytesIO
    data = BytesIO()
    font.save(data)
    font.close()
    content = data.getvalue()
    digest = hashlib.sha256(content).hexdigest()[:12]
    name = f"{stem}.{digest}.woff2"
    (output / name).write_bytes(content)
    return name


def font_face(family, filename, weight, style, local, ranges=None):
    """优先使用已安装字体；下载期间保持系统回退字体可见。"""
    rule = (f'@font-face {{\n  font-family: "{family}";\n  font-display: swap;\n'
            f'  src: local("{local}"), url("../fonts/web/{filename}") format("woff2");\n'
            f'  font-weight: {weight};\n  font-style: {style};\n')
    if ranges:
        rule += f"  unicode-range: {ranges};\n"
    return rule + "}"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fonts", action="store_true", help="Rebuild WOFF2 fonts (requires fonttools and brotli)")
    args = parser.parse_args()
    if args.fonts:
        build_fonts()
    bundle("theme.bundle.css", ["libs/normalize.css", "libs/grid.css", "assets/css/font.css",
                                "assets/css/style.css", "assets/css/friend-card.css",
                                "utils/cjk-latin-spacing/cjk-latin-spacing.css"])
    # 字体定义独立于首屏代码样式：只在代码接近视口后由主题加载器请求。
    bundle("code.bundle.css", ["libs/prism/prism.css", "assets/css/prism-replicon.css"])
    print("Stylesheets built.")
