"""下载 Noto Serif SC 官方 WOFF2 分片，生成只引用本服务器文件的正文样式表。"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import time
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets/fonts/NotoSerifSC"
CSS_URL = "https://fonts.googleapis.com/css2?family=Noto+Serif+SC:wght@400;700&display=swap"
LICENSE_URL = "https://raw.githubusercontent.com/google/fonts/main/ofl/notoserifsc/OFL.txt"
USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"


def download(url):
    """只在开发者主动执行此脚本时联网；请求失败时有限重试，不影响线上页面。"""
    for attempt in range(3):
        try:
            with urlopen(Request(url, headers={"User-Agent": USER_AGENT}), timeout=45) as response:
                return response.read()
        except OSError:
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def main(refresh):
    OUTPUT.mkdir(parents=True, exist_ok=True)
    upstream = OUTPUT / "upstream.css"
    if refresh or not upstream.exists():
        upstream.write_bytes(download(CSS_URL))
    if refresh or not (OUTPUT / "OFL.txt").exists():
        (OUTPUT / "OFL.txt").write_bytes(download(LICENSE_URL))
    text = upstream.read_text(encoding="utf-8-sig")
    urls = sorted(set(re.findall(r"https://fonts\.gstatic\.com/[^)\s]+\.woff2", text)))
    if not urls:
        raise RuntimeError("官方响应不包含 WOFF2 字体，停止生成以免覆盖有效配置")

    # 只允许固定字体域名和格式，避免把样式表中的其他 URL 当成下载任务。
    # 缓存清单同时保存完整 SHA-256，重复运行无需再次下载已有且校验通过的字体。
    manifest_path = OUTPUT / "SOURCE.json"
    cached = json.loads(manifest_path.read_text(encoding="utf-8"))["files"] if manifest_path.exists() else {}

    def vendor(item):
        index, url = item
        entry = cached.get(url)
        if entry and (OUTPUT / entry["file"]).is_file():
            content = (OUTPUT / entry["file"]).read_bytes()
            if hashlib.sha256(content).hexdigest() == entry["sha256"]:
                return url, entry
        content = download(url)
        if content[:4] != b"wOF2":
            raise RuntimeError("字体响应不是 WOFF2，拒绝保存：" + url)
        digest = hashlib.sha256(content).hexdigest()
        filename = f"NotoSerifSC-{index:03}.{digest[:12]}.woff2"
        (OUTPUT / filename).write_bytes(content)
        return url, {"file": filename, "sha256": digest, "bytes": len(content)}

    with ThreadPoolExecutor(max_workers=4) as pool:
        files = dict(pool.map(vendor, enumerate(urls)))

    rules = []
    seen = set()
    for rule in re.findall(r"@font-face\s*\{[^}]+\}", text):
        url = re.search(r"https://fonts\.gstatic\.com/[^)\s]+\.woff2", rule)
        if not url or url.group(0) not in files:
            raise RuntimeError("存在未下载的字体声明，拒绝生成不完整样式")
        rule = rule.replace(url.group(0), "../fonts/NotoSerifSC/" + files[url.group(0)]["file"])
        # 官方为两个字重重复声明同一份可变字体；合并后仍覆盖 400 和 700。
        # 使用专用 family 名称，确保本服务器模式确实选中这套自托管字体。
        rule = rule.replace("'Noto Serif SC'", "'Replicon Noto Serif SC'")
        rule = re.sub(r"font-weight:\s*(?:400|700);", "font-weight: 400 700;", rule)
        if rule not in seen:
            seen.add(rule)
            rules.append(rule)
    header = "/* Generated by tools/vendor_serif_font.py; self-hosted Noto Serif SC. */\n"
    (ROOT / "assets/css/serif.css").write_text(header + "\n\n".join(rules) + "\n", encoding="utf-8", newline="\n")
    manifest = {"stylesheet": CSS_URL, "license": LICENSE_URL, "files": files}
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Self-hosted serif: {len(files)} files, {sum(f['bytes'] for f in files.values())} bytes; {len(rules)} CSS rules.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true", help="重新获取官方字体 CSS 和许可证")
    main(parser.parse_args().refresh)
